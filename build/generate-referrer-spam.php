<?php
/**
 * Regenerates data/referrer-spam.php from Matomo's referrer spam list.
 *
 *   php build/generate-referrer-spam.php [path-or-url-to-spammers.txt]
 *
 * Source: https://github.com/matomo-org/referrer-spam-list (spammers.txt),
 * public domain. One registrable domain per line; Referrer_Spam matches a
 * host when it equals an entry or ends in ".<entry>", so subdomains are
 * covered without listing them.
 */

declare(strict_types=1);

$source = $argv[1] ?? 'https://raw.githubusercontent.com/matomo-org/referrer-spam-list/master/spammers.txt';
$raw    = file_get_contents( $source );
if ( false === $raw || '' === trim( $raw ) ) {
	fwrite( STDERR, "could not read {$source}\n" );
	exit( 1 );
}

$hosts = [];
foreach ( preg_split( '/\R/', $raw ) as $line ) {
	$line = strtolower( trim( $line ) );
	if ( '' === $line || '#' === $line[0] ) {
		continue;
	}
	if ( 0 === strpos( $line, 'www.' ) ) {
		$line = substr( $line, 4 );
	}
	// A host, nothing else: no paths, no schemes, no wildcards.
	if ( 1 !== preg_match( '/^[a-z0-9.-]+\.[a-z0-9-]+$/', $line ) ) {
		continue;
	}
	$hosts[ $line ] = true;
}
ksort( $hosts );

$commit = getenv( 'SPAM_LIST_COMMIT' ) ?: 'master';
$out    = "<?php\n/**\n * Referrer spam hosts.\n *\n * Generated by build/generate-referrer-spam.php from\n * matomo-org/referrer-spam-list (spammers.txt at {$commit}), public domain.\n * One registrable domain per entry; subdomains match by suffix.\n *\n * Regenerate rather than hand-edit.\n *\n * @return array<int,string>\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn [\n";
foreach ( array_keys( $hosts ) as $host ) {
	$out .= "\t" . var_export( $host, true ) . ",\n";
}
$out .= "];\n";

$target = __DIR__ . '/../data/referrer-spam.php';
file_put_contents( $target, $out );
echo count( $hosts ) . " hosts written to data/referrer-spam.php\n";
