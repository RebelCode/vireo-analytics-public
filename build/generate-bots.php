<?php
/**
 * Regenerates data/bots.php from device-detector's bot list.
 *
 * Usage:
 *   php build/generate-bots.php            # the pinned commit below
 *   php build/generate-bots.php <commit>   # another commit, branch or tag
 *
 * To move to a newer upstream, pass its commit SHA, check the result with
 * tests/test-bot-filter.php, then update PINNED_REF so the next run without
 * an argument reproduces the file.
 *
 * Bot_Filter's own hand-written CATEGORY_PATTERNS live in
 * includes/class-bot-filter.php and are not touched here.
 */

const PINNED_REF = 'e83ce7a97f05d8ee3e1eee7ea77a73b3bdfebd9a';
const SOURCE_URL = 'https://raw.githubusercontent.com/matomo-org/device-detector/%s/regexes/bots.yml';

// Our category for each device-detector category. Anything not listed,
// including an entry with no category, goes to `other`.
const CATEGORY_MAP = [
	'AI Agent'           => 'ai',
	'AI Assistant'       => 'ai',
	'AI Data Scraper'    => 'ai',
	'AI Search Crawler'  => 'ai',
	'Site Monitor'       => 'uptime',
	'Social Media Agent' => 'social',
	'Search bot'         => 'search',
	'Search tools'       => 'search',
	'Validator'          => 'archive',
	'Benchmark'          => 'automation',
];

// Output order. Bot_Filter tries every category but `other` first, so this
// only decides which of two named categories wins when both match.
const OUTPUT_ORDER = [ 'ai', 'uptime', 'social', 'search', 'archive', 'automation', 'other' ];

define( 'ABSPATH', dirname( __DIR__ ) . '/' );
require ABSPATH . 'includes/class-bot-filter.php';

function fail( string $message ): void {
	fwrite( STDERR, $message . "\n" );
	exit( 1 );
}

/**
 * A YAML scalar as device-detector writes them: single-quoted ('' is a
 * quote) or double-quoted (only \\ and \" escapes). Anything else stops the
 * run rather than risk a silently wrong pattern.
 */
function yaml_scalar( string $raw, int $line ): string {
	$raw = trim( $raw );
	if ( preg_match( "/^'((?:[^']|'')*)'$/", $raw, $m ) ) {
		return str_replace( "''", "'", $m[1] );
	}
	if ( preg_match( '/^"((?:[^"\\\\]|\\\\.)*)"$/', $raw, $m ) ) {
		if ( preg_match( '/\\\\[^\\\\"]/', $m[1] ) ) {
			fail( "Line $line: unsupported escape in $raw" );
		}
		return str_replace( [ '\\\\', '\\"' ], [ '\\', '"' ], $m[1] );
	}
	fail( "Line $line: unquoted or malformed value $raw" );
}

/**
 * @return array<int, array{regex:string, category:string}>
 */
function parse_bots_yml( string $yaml ): array {
	$entries = [];
	foreach ( preg_split( '/\R/', $yaml ) as $i => $line ) {
		if ( preg_match( '/^- regex:(.*)$/', $line, $m ) ) {
			$entries[] = [ 'regex' => yaml_scalar( $m[1], $i + 1 ), 'category' => '' ];
		} elseif ( preg_match( '/^  category:(.*)$/', $line, $m ) && $entries ) {
			$entries[ count( $entries ) - 1 ]['category'] = yaml_scalar( $m[1], $i + 1 );
		} elseif ( preg_match( '/^-/', $line ) ) {
			fail( 'Line ' . ( $i + 1 ) . ': entry does not start with regex' );
		}
	}
	return $entries;
}

/** Escapes an unescaped `~`, Bot_Filter's regex delimiter. */
function escape_delimiter( string $pattern ): string {
	return preg_replace( '/(?<!\\\\)((?:\\\\\\\\)*)~/', '$1\\~', $pattern );
}

function php_literal( string $value ): string {
	return "'" . str_replace( [ '\\', "'" ], [ '\\\\', "\\'" ], $value ) . "'";
}

$ref  = $argv[1] ?? PINNED_REF;
$yaml = @file_get_contents( sprintf( SOURCE_URL, rawurlencode( $ref ) ) );
if ( false === $yaml || '' === $yaml ) {
	fail( "Could not fetch bots.yml at $ref" );
}

$entries = parse_bots_yml( $yaml );
if ( count( $entries ) < 500 ) {
	fail( 'Parsed only ' . count( $entries ) . ' entries; the format has probably changed.' );
}

$groups = array_fill_keys( OUTPUT_ORDER, [] );
foreach ( $entries as $entry ) {
	$groups[ CATEGORY_MAP[ $entry['category'] ] ?? 'other' ][] = '(?:' . $entry['regex'] . ')';
}

$rows = '';
foreach ( $groups as $key => $patterns ) {
	if ( ! $patterns ) {
		continue;
	}
	$pattern = escape_delimiter( implode( '|', $patterns ) );
	if ( false === @preg_match( \VireoAnalytics\Bot_Filter::extended_regex( $pattern ), '' ) ) {
		fail( "The $key pattern does not compile: " . preg_last_error_msg() );
	}
	$rows .= "\t'$key' => " . php_literal( $pattern ) . ",\n";
}

$counts = implode( ', ', array_map( static fn( $k, $v ) => "$k " . count( $v ), array_keys( $groups ), $groups ) );

$out = <<<PHP
<?php
/**
 * Bot signatures, grouped by category.
 *
 * Generated by build/generate-bots.php from the device-detector bot regexes
 * (matomo-org/device-detector, regexes/bots.yml at commit $ref),
 * LGPL-3.0, which is compatible with this plugin's GPL-3.0 licence. Only the
 * patterns and their categories are used; the library itself is not bundled,
 * because it is larger than this entire plugin.
 *
 * Bot_Filter matches each pattern from the start of a token, as
 * device-detector does, and tries every category before `other`.
 *
 * Regenerate rather than hand-edit.
 *
 * @return array<string,string> category => combined regex
*/

defined( 'ABSPATH' ) || exit;

return [
$rows];

PHP;

file_put_contents( ABSPATH . 'data/bots.php', $out );
echo 'Wrote data/bots.php from ' . count( $entries ) . " entries at $ref ($counts)\n";
